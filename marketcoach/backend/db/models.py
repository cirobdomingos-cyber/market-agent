from datetime import datetime, timezone
import uuid

from sqlalchemy import (
    Boolean,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
)
from sqlalchemy.orm import DeclarativeBase


def _now_utc() -> datetime:
    return datetime.now(timezone.utc)


def _uuid() -> str:
    return str(uuid.uuid4())


class Base(DeclarativeBase):
    pass


class Signal(Base):
    """One piece of news-derived market signal for a specific ticker."""

    __tablename__ = "signals"

    id = Column(String, primary_key=True, default=_uuid)
    ticker = Column(String, nullable=False, index=True)
    sentiment = Column(String, nullable=False)  # bullish | bearish | neutral
    confidence = Column(Float, nullable=False)   # 0.0 – 1.0
    source = Column(String, nullable=False)
    headline = Column(Text, nullable=False)
    raw_text = Column(Text)
    created_at = Column(DateTime, default=_now_utc)


class Thesis(Base):
    """A structured market thesis generated by the analysis agent."""

    __tablename__ = "theses"

    id = Column(String, primary_key=True, default=_uuid)
    ticker = Column(String, nullable=False, index=True)
    direction = Column(String, nullable=False)   # bullish | bearish | neutral
    confidence = Column(Float, nullable=False)   # 0.0 – 1.0
    timeframe = Column(String, nullable=False)   # e.g. "3-10 days"
    reasoning = Column(Text, nullable=False)
    key_risks = Column(Text, nullable=False)     # JSON-serialised list[str]
    created_at = Column(DateTime, default=_now_utc)
    resolved_at = Column(DateTime, nullable=True)
    outcome = Column(String, nullable=True)      # correct | incorrect | partial
    accuracy = Column(Float, nullable=True)      # price-change accuracy score


class TradeIdea(Base):
    """Actionable trade idea generated from a thesis — the bridge from analysis to execution."""
    __tablename__ = "trade_ideas"

    id = Column(String, primary_key=True, default=_uuid)
    thesis_id = Column(String, ForeignKey("theses.id"), nullable=False)
    ticker = Column(String, nullable=False, index=True)

    # Direction & strategy
    direction = Column(String, nullable=False)       # long | short
    strategy = Column(String, nullable=False)         # equity_long | equity_short | hold | avoid
    horizon = Column(String, nullable=False)          # short (1-5d) | medium (1-4w) | long (1-3m)

    # Price levels
    entry_price = Column(Float, nullable=False)       # suggested entry price
    stop_loss = Column(Float, nullable=False)          # stop-loss price
    take_profit = Column(Float, nullable=False)        # take-profit target
    current_price = Column(Float, nullable=False)      # price at time of generation

    # Sizing & risk
    confidence = Column(Float, nullable=False)         # 0.0-1.0 from thesis
    risk_reward_ratio = Column(Float, nullable=False)  # reward / risk
    position_size_pct = Column(Float, nullable=False)  # % of portfolio to allocate
    max_loss_pct = Column(Float, nullable=False)       # max loss as % of portfolio

    # Rationale
    rationale = Column(Text, nullable=False)           # why this trade, in plain language
    key_levels = Column(Text)                          # JSON: support/resistance levels

    # Lifecycle
    status = Column(String, default="active")          # active | executed | expired | cancelled
    created_at = Column(DateTime, default=_now_utc)
    expires_at = Column(DateTime, nullable=True)       # when the idea becomes stale
    executed_at = Column(DateTime, nullable=True)


